// קריאת משתני סביבה. Netlify חושפת אותם דרך Netlify.env, ובסביבות
// מקומיות דרך process.env. התמיכה בשניהם מונעת תלות בסביבה אחת.
function envVar(name) {
  try {
    const v = globalThis.Netlify?.env?.get?.(name);
    if (v) return v;
  } catch {}
  return globalThis.process?.env?.[name];
}

// כתובות נוספות שמהן מותר לקרוא ל-API, מעבר לכתובת שבה הבוט עצמו יושב.
// דרוש רק אם מטמיעים את הבוט בתוך אתר אחר.
const ALLOWED_ORIGINS = ["https://sw.huji.ac.il"];

const MODEL = "claude-sonnet-4-6";
const MAX_TOKENS = 1000;
const MAX_MESSAGES = 30;
const MAX_CHARS = 4000;
const RATE_LIMIT = 20;        // בקשות
const RATE_WINDOW = 60_000;   // בפרק זמן, במילישניות

// אותן בדיקות שבדפדפן, גם כאן: הדפדפן אינו קו ההגנה היחיד.
const PERSONAL_PATTERNS = [
  /(ת\.?\s?ז|ת"ז|תעודת\s*זהות|מספר\s*זהות)\D{0,12}\d{3,}/,
  /[A-Za-z0-9._%+-]+@(?!(?:[A-Za-z0-9-]+\.)*huji\.ac\.il\b)[A-Za-z0-9.-]+\.[A-Za-z]{2,}/,
  /(^|[^\d])0\d{1,2}[-\s]?\d{7}([^\d]|$)/,
  /(^|[^\d])\d{10,}([^\d]|$)/,
];

function hasPersonal(text) {
  return PERSONAL_PATTERNS.some((re) => re.test(text));
}

// מתקבל טקסט בלבד. קבצים אינם נתמכים, כדי שלא ייווצר ערוץ להעלאת
// מסמכים אישיים דרך השירות.
function validContent(content) {
  return typeof content === "string" && content.length > 0 && content.length <= MAX_CHARS;
}

// מונה בקשות לפי כתובת IP. המונה חי בזיכרון המופע, ולכן הוא מרסן
// שימוש אוטומטי אך אינו תקרה מוחלטת. ההגנה המחייבת היא תקרת
// ההוצאה בחשבון ה-API.
const hits = new Map();
function rateLimited(ip) {
  const now = Date.now();
  const recent = (hits.get(ip) || []).filter((t) => now - t < RATE_WINDOW);
  recent.push(now);
  hits.set(ip, recent);
  if (hits.size > 5000) hits.clear();
  return recent.length > RATE_LIMIT;
}

function cors(origin) {
  return {
    "Access-Control-Allow-Origin": origin || ALLOWED_ORIGINS[0],
    "Access-Control-Allow-Headers": "Content-Type",
    "Access-Control-Allow-Methods": "POST, OPTIONS",
  };
}

function fail(status, message, origin) {
  return new Response(JSON.stringify({ error: message }), {
    status,
    headers: { "Content-Type": "application/json", ...cors(origin) },
  });
}

export default async (request, context) => {
  const origin = request.headers.get("Origin");
  const sameOrigin = origin === new URL(request.url).origin;

  if (request.method === "OPTIONS") {
    return new Response(null, { status: 204, headers: cors(origin) });
  }
  if (request.method !== "POST") {
    return fail(405, "שיטה לא נתמכת", origin);
  }
  if (origin && !sameOrigin && !ALLOWED_ORIGINS.includes(origin)) {
    return fail(403, "מקור לא מורשה", origin);
  }

  const apiKey = envVar("ANTHROPIC_API_KEY");
  if (!apiKey) {
    return fail(500, "המפתח אינו מוגדר בשרת", origin);
  }

  let body;
  try {
    body = await request.json();
  } catch {
    return fail(400, "בקשה לא תקינה", origin);
  }

  const ip = context?.ip || request.headers.get("x-nf-client-connection-ip") || "unknown";
  if (rateLimited(ip)) {
    return fail(429, "נשלחו יותר מדי שאלות בזמן קצר. נסו שוב בעוד דקה.", origin);
  }

  // אימות Turnstile. פועל רק אם הוגדר המשתנה TURNSTILE_SECRET;
  // בלעדיו הבדיקה מדולגת והבוט ממשיך לעבוד.
  const secret = envVar("TURNSTILE_SECRET");
  if (secret) {
    const token = typeof body?.turnstileToken === "string" ? body.turnstileToken : "";
    if (!token) return fail(403, "האימות נכשל. רעננו את הדף ונסו שוב.", origin);
    const form = new FormData();
    form.append("secret", secret);
    form.append("response", token);
    if (ip && ip !== "unknown") form.append("remoteip", ip);
    const verify = await fetch("https://challenges.cloudflare.com/turnstile/v0/siteverify", {
      method: "POST",
      body: form,
    });
    const outcome = await verify.json();
    if (!outcome.success) {
      // Cloudflare מחזירה קוד מדויק. מציגים אותו, אחרת אי אפשר לאבחן.
      const codes = (outcome["error-codes"] || []).join(", ");
      const why = {
        "invalid-input-secret": "המפתח הסודי שהוזן בשרת אינו תקין",
        "missing-input-secret": "לא הוגדר מפתח סודי בשרת",
        "invalid-input-response": "האסימון מהדפדפן אינו תקין — ייתכן שה-Sitekey וה-Secret שייכים לווידג'טים שונים, או שכתובת האתר אינה רשומה בווידג'ט",
        "timeout-or-duplicate": "האסימון פג או כבר נוצל",
        "bad-request": "הבקשה לאימות אינה תקינה",
      }[codes] || "סיבה לא מזוהה";
      return fail(403, `האימות נכשל: ${why} (${codes || "ללא קוד"})`, origin);
    }
  }

  const messages = Array.isArray(body?.messages) ? body.messages : null;
  if (!messages || messages.length === 0 || messages.length > MAX_MESSAGES) {
    return fail(400, "מבנה ההודעות אינו תקין", origin);
  }
  for (const m of messages) {
    if ((m.role !== "user" && m.role !== "assistant") || !validContent(m.content)) {
      return fail(400, "מבנה ההודעות אינו תקין", origin);
    }
    if (m.role === "user" && hasPersonal(m.content)) {
      return fail(400, 'הסימולטור עונה על שאלות כלליות בלבד ואינו קולט פרטים מזהים. לפנייה אישית יש לכתוב לרכזת התוכנית בדוא"ל.', origin);
    }
  }

  // הפרומפט, המודל ותקרת האורך נקבעים כאן ולא בדפדפן, כדי שלא יהיה אפשר
  // להשתמש בנתיב הזה כ-Claude חופשי על חשבון בית הספר.
  const upstream = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "x-api-key": apiKey,
      "anthropic-version": "2023-06-01",
    },
    body: JSON.stringify({
      model: MODEL,
      max_tokens: MAX_TOKENS,
      // הפרומפט זהה בכל פנייה, ולכן הוא נשמר במטמון אצל אנתרופיק.
      // קריאה מהמטמון עולה עשירית ממחיר קלט רגיל.
      system: [{ type: "text", text: SYSTEM_PROMPT, cache_control: { type: "ephemeral" } }],
      messages: messages.map((m) => ({ role: m.role, content: m.content })),
    }),
  });

  if (!upstream.ok) {
    const detail = await upstream.text();
    return new Response(
      JSON.stringify({ error: "השירות אינו זמין", status: upstream.status, detail: detail.slice(0, 300) }),
      { status: 502, headers: { "Content-Type": "application/json", ...cors(origin) } }
    );
  }

  const data = await upstream.json();
  return new Response(JSON.stringify({ content: data.content }), {
    headers: { "Content-Type": "application/json", ...cors(origin) },
  });
};

